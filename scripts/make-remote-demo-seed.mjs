#!/usr/bin/env node
/**
 * Derives the remote demo seed from the local one.
 *
 * `supabase/seed.sql` refuses to run anywhere except a local stack: it compares
 * the JWT secret against the well-known local value. That guard exists so
 * synthetic rows can never land in a database that holds real tenants, and it
 * is not something to delete.
 *
 * A hosted demo environment still needs the data. So the guard is not removed,
 * it is repointed: the remote copy refuses every database where
 * private.demo_environment is empty. That table ships in every environment
 * (see the 20260802040000 migration); only a demonstration database is given a
 * row, by hand.
 *
 * The production project never receives that row, so this file cannot seed it —
 * the failure is a raised exception, not a silent partial insert, because the
 * whole seed runs inside one transaction.
 *
 * Regenerate after any change to supabase/seed.sql:
 *   node scripts/make-remote-demo-seed.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'supabase', 'seed.sql');
const target = join(root, 'supabase', 'seed', 'remote_demo_seed.sql');

const LOCAL_GUARD = `do $$
begin
 if coalesce(current_setting('app.settings.jwt_secret',true),'') <> 'super-secret-jwt-token-with-at-least-32-characters-long' then
  raise exception 'QADAM demo seed is local/dev-only. Refusing non-local database.';
 end if;
end $$;`;

const REMOTE_GUARD = `-- Generated by scripts/make-remote-demo-seed.mjs — do not edit by hand.
-- Only a database a human has explicitly marked as a demo environment accepts this.
do $$
begin
 if not exists (select 1 from private.demo_environment) then
  raise exception 'QADAM demo seed refuses this database: private.demo_environment is empty, so it is not a demonstration environment. Mark the demo project explicitly, and never the production one.';
 end if;
end $$;`;

// Git hands this file CRLF on a Windows checkout, and the guard is matched as
// an exact string. Normalising first means the generator does not depend on how
// the repository happened to be cloned; the output is written LF either way, so
// Postgres and the guard checks see the same bytes everywhere.
const sql = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
if (!sql.includes(LOCAL_GUARD)) {
  console.error('FAIL: the local-only guard in supabase/seed.sql no longer matches.');
  console.error('Refusing to generate a remote seed without a guard. Update this script deliberately.');
  process.exit(1);
}

// A function replacer, not a string: `$$` in a replacement string is an escape
// for a literal `$`, which would quietly break every dollar-quoted block.
const remote = sql.replace(LOCAL_GUARD, () => REMOTE_GUARD);
if (remote.includes('jwt_secret')) {
  console.error('FAIL: the local guard survived the rewrite.');
  process.exit(1);
}
if (!remote.includes('do $$') || !remote.includes('end $$;')) {
  console.error('FAIL: dollar quoting did not survive the rewrite.');
  process.exit(1);
}

writeFileSync(target, remote, 'utf8');
console.log(`PASS: wrote ${target} (${remote.length} bytes, guarded by a row in private.demo_environment).`);
