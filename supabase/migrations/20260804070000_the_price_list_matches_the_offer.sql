-- Один прайс-лист вместо двух.
--
-- Цены жили в двух местах и разошлись: витрина `/pricing` показывала
-- 29 000 / 59 000 / 99 000 под названиями «Старт / Рост / Сеть», а таблица
-- `public.plans`, из которой сервер считает лимиты, — 9 900 / 24 900 / 49 900
-- под кодами `start / growth / pro`. Владелец видел одну цену, а платил бы по
-- другой; это не опечатка, а два источника истины.
--
-- Утверждённый прайс: Standard 9 900 ₸, Growth 59 900 ₸, Pro 99 000 ₸.
-- `price_minor` здесь хранит целые тенге — так его форматирует кабинет
-- (`Intl.NumberFormat` без дробной части), и менять единицу измерения задним
-- числом означало бы переписать все существующие подписки.
--
-- Код `start` переименован в `standard`: название на витрине и код в базе
-- должны читаться как одно и то же. `subscriptions` ссылаются на `plans.id`,
-- а не на код, поэтому переименование никого не отвязывает.

update public.plans set code = 'standard', name = 'Standard' where code = 'start';

update public.plans set price_minor = 9900,
  description_ru = 'Для одной точки, которая уже работает с постоянными гостями.',
  description_kk = 'Тұрақты қонақтармен жұмыс істейтін бір нүктеге.'
where code = 'standard';

update public.plans set price_minor = 59900, name = 'Growth',
  description_ru = 'Для растущего бизнеса: несколько каналов, команда и автоматизации.',
  description_kk = 'Өсіп келе жатқан бизнеске: бірнеше арна, команда және автоматтандыру.'
where code = 'growth';

update public.plans set price_minor = 99000, name = 'Pro',
  description_ru = 'Для сети точек с большой базой и полным набором автоматизаций.',
  description_kk = 'Үлкен базасы және толық автоматтандыруы бар нүктелер желісіне.'
where code = 'pro';

-- Витрина цен — публичная страница, и до сих пор она перечисляла тарифы
-- вручную только потому, что `anon` не имел права их прочитать. Цена — не
-- тайна: открываем ровно то, что и так напечатано на странице, и ровно в том
-- же объёме, что видит вошедший пользователь.
create policy plans_anon_select on public.plans
  for select to anon
  using (status = 'active' and is_public);

grant select on table public.plans to anon;
