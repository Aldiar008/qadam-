-- Стоматология как тип заведения.
--
-- Продукт заявляет, что подходит любому офлайн-бизнесу, а список типов состоял
-- из кофейни, салона, магазина и сервисной точки. Стоматология — ровно тот
-- случай, на котором заявление проверяется: там пациенты, приёмы, врачи и
-- процедуры, и ни одно из этих слов не появилось бы само.
--
-- Словарь живёт в `src/domain/business-vocabulary.ts` и подставляется по этому
-- коду. Тип, которого в словаре нет, получает нейтральные слова — «клиент» и
-- «визит» безопасны везде, а угадывать нельзя.

insert into public.business_types(code, name_ru, name_kk, status, is_public)
values ('dental', 'Стоматология', 'Стоматология', 'published', true)
on conflict (code) do update set
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  status = 'published';
