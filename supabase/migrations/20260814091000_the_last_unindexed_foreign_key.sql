-- Последний внешний ключ без индекса.
--
-- `001_schema_security` требует, чтобы каждая колонка внешнего ключа была
-- проиндексирована: без этого база при удалении родительской строки читает
-- дочернюю таблицу целиком, чтобы проверить ссылочную целостность. Проверка
-- падала на `customer_interactions.answered_interaction_id` — колонка приехала
-- вместе с центром обращений 4 августа, а индекс к ней не приехал.
--
-- Правка вынесена отдельной миграцией, а не дописана к миграции про остатки:
-- у неё своя причина и своя область, и через месяц это будет видно из истории.

create index if not exists customer_interactions_answered_fk_idx
  on public.customer_interactions(answered_interaction_id);

commit;
