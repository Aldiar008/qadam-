/** Повод по коду — для экранов, которые получают из базы только код. */
export function holidayByCode(code: string): Holiday | undefined {
  return HOLIDAYS.find((holiday) => holiday.code === code);
}

/**
 * Ближайшая дата повода от переданного дня.
 *
 * Год не берётся из текущего момента внутри функции: время — это вход, а не
 * скрытое состояние, иначе один и тот же расчёт даёт разный ответ в зависимости
 * от того, когда его запустили, и его нельзя проверить тестом.
 */
export function nextOccurrence(holiday: Holiday, from: Date): Date {
  const thisYear = new Date(Date.UTC(from.getUTCFullYear(), holiday.month - 1, holiday.day));
  if (thisYear.getTime() >= from.getTime()) return thisYear;
  return new Date(Date.UTC(from.getUTCFullYear() + 1, holiday.month - 1, holiday.day));
}

/** Сколько суток осталось до повода. Отрицательных не бывает: повод всегда впереди. */
export function daysUntil(holiday: Holiday, from: Date): number {
  const target = nextOccurrence(holiday, from);
  return Math.ceil((target.getTime() - from.getTime()) / 86_400_000);
}

/** Повод действует, когда до него осталось не больше его собственного окна. */
export function isInWindow(holiday: Holiday, from: Date): boolean {
  return daysUntil(holiday, from) <= holiday.windowDays;
}
